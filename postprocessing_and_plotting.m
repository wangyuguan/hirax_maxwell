%% Self-convergence

% Scattered electric field at all probe points.
reference_values = reference_level.escat(:);
reference_point_maximum = max(abs(reference_values));

% Surface-quadrature-weighted L2 norm of the three-component tangential
% surface current. The fourth density row is the scalar charge.
surface_weights = reference_data.S.wts(:).';
surface_current = reference_data.densities(1:3,:);
surface_current_point_energy = sum(abs(surface_current).^2,1);
reference_surface_current_norm = sqrt(real(sum( ...
    surface_weights.*surface_current_point_energy)));

comparison_orders = completed_orders(1:end-1);
