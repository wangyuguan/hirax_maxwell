    number_of_outline_panels*number_of_wall_panels-1;
lower_wall_start = upper_wall_end+1;
lower_wall_end = lower_wall_start+ ...
    number_of_outline_panels*number_of_wall_panels-1;
bottom_collar_patches = lower_wall_end+(1:number_of_outline_panels);

top_wall_join_uv = [zeros(1,number_of_outline_panels); ...
    -ones(1,number_of_outline_panels)];
