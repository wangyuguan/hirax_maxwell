    '$A^{\prime}$','$B^{\prime}$','$C^{\prime}$','$D^{\prime}$'};

% Extend both paths through A and A' into the adjacent top-core triangle.
% This provides independent limits from the core and collar sides.
triangle_vertex_uv = [0 1 0;0 0 1];
triangle_edge_vertices = [1 2;2 3;3 1];
triangle_opposite_vertex = [3 1 2];
core_vertex_patch_ids = repelem( ...
    1:number_of_core_triangles,3);
core_vertex_uv = repmat( ...
    triangle_vertex_uv,1,number_of_core_triangles);
core_vertex_points = interpolate_data( ...
    S,S.r,core_vertex_patch_ids,core_vertex_uv);
core_vertex_points = reshape( ...
    core_vertex_points,3,3,number_of_core_triangles);

path_start_points = {continuity_points(:,1),off_source_points(:,1)};
core_extension_points = cell(1,2);
core_extension_values = cell(1,2);
core_extension_arclengths = cell(1,2);
for path_id = 1:2
    edge_midpoint_error = zeros(3,number_of_core_triangles);
    for edge_id = 1:3
        edge_vertices = triangle_edge_vertices(edge_id,:);
        edge_midpoints = 0.5*( ...
            core_vertex_points(:,edge_vertices(1),:)+ ...
            core_vertex_points(:,edge_vertices(2),:));
        edge_midpoints = reshape( ...
            edge_midpoints,3,number_of_core_triangles);
        edge_midpoint_error(edge_id,:) = vecnorm( ...
            edge_midpoints-path_start_points{path_id},2,1);
    end
    [~,closest_edge] = min(edge_midpoint_error(:));
    [edge_id,core_patch] = ind2sub( ...
        size(edge_midpoint_error),closest_edge);
    edge_vertices = triangle_edge_vertices(edge_id,:);
    edge_midpoint_uv = 0.5*( ...
        triangle_vertex_uv(:,edge_vertices(1))+ ...
        triangle_vertex_uv(:,edge_vertices(2)));
    opposite_uv = triangle_vertex_uv(:, ...
        triangle_opposite_vertex(edge_id));
    core_path_parameter = linspace(1,0,path_points_per_patch);
    core_path_uv = opposite_uv.*core_path_parameter+ ...
        edge_midpoint_uv.*(1-core_path_parameter);
    core_path_patch_ids = core_patch*ones(1,path_points_per_patch);
    core_extension_points{path_id} = interpolate_data( ...
        S,S.r,core_path_patch_ids,core_path_uv);
    core_extension_values{path_id} = interpolate_data( ...
        S,reference_data.densities,core_path_patch_ids,core_path_uv);
    core_arclength = geometry_display_scale*[0 cumsum(vecnorm( ...
        diff(core_extension_points{path_id},1,2),2,1))];
    core_extension_arclengths{path_id} = ...
        core_arclength-core_arclength(end);
end

