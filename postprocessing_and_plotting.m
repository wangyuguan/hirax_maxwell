    level = completed_levels{order_id};
    current_values = level.escat(:);
    maximum_absolute_difference(order_id) = max(abs( ...
        current_values-reference_values));
    normalized_by_point_value(order_id) = ...
        maximum_absolute_difference(order_id)/reference_point_maximum;
    normalized_by_surface_current_norm(order_id) = ...
        maximum_absolute_difference(order_id)/ ...
        reference_surface_current_norm;
end

digits_by_point_value = -log10(normalized_by_point_value);
digits_by_surface_current_norm = ...
    -log10(normalized_by_surface_current_norm);
