    order_step = comparison_orders(order_id+1)- ...
        comparison_orders(order_id);
    digits_gained_per_surface_order(order_id) = ...
        (digits_by_point_value(order_id+1)- ...
        digits_by_point_value(order_id))/order_step;
end

