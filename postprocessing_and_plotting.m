    S,S.r,top_collar_patches,top_wall_join_uv);
[~,source_side_panel] = min(vecnorm( ...
    top_wall_join_points(1:2,:)-source_point(1:2),2,1));
off_source_offset = round(number_of_outline_panels/8);
off_source_candidates = 1+mod( ...
    source_side_panel-1+[-off_source_offset off_source_offset], ...
    number_of_outline_panels);
[~,off_source_candidate_id] = min(vecnorm( ...
    top_wall_join_points(1:2,off_source_candidates)- ...
    source_point(1:2),2,1));
off_source_panel = off_source_candidates(off_source_candidate_id);

source_side_upper_wall = upper_wall_start+ ...
    (source_side_panel-1)*number_of_wall_panels+ ...
    (0:number_of_wall_panels-1);
source_side_lower_wall = lower_wall_start+ ...
    (source_side_panel-1)*number_of_wall_panels+ ...
    (0:number_of_wall_panels-1);
continuity_path_patches = [ ...
    top_collar_patches(source_side_panel), ...
    source_side_upper_wall,source_side_lower_wall, ...
    bottom_collar_patches(source_side_panel)];

off_source_upper_wall = upper_wall_start+ ...
    (off_source_panel-1)*number_of_wall_panels+ ...
    (0:number_of_wall_panels-1);
off_source_lower_wall = lower_wall_start+ ...
    (off_source_panel-1)*number_of_wall_panels+ ...
    (0:number_of_wall_panels-1);
off_source_path_patches = [ ...
    top_collar_patches(off_source_panel), ...
    off_source_upper_wall,off_source_lower_wall, ...
    bottom_collar_patches(off_source_panel)];

path_points_per_patch = 101;
path_local_coordinate = linspace(-1,1,path_points_per_patch);
number_of_path_patches = numel(continuity_path_patches);
continuity_patch_ids = repelem( ...
    continuity_path_patches,path_points_per_patch);
continuity_uv = zeros(2,numel(continuity_patch_ids));
for path_patch = 1:number_of_path_patches
    path_ids = (path_patch-1)*path_points_per_patch+ ...
        (1:path_points_per_patch);
    if path_patch==1
        continuity_uv(:,path_ids) = [ ...
            zeros(1,path_points_per_patch); ...
